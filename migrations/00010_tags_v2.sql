-- Every (ancestor, descendant) pair, including each tag with itself at
-- depth 0. Rebuilt from tag_parents whenever the tree changes.
CREATE TABLE tag_closure (
    ancestor_id   integer NOT NULL REFERENCES tags(id) ON DELETE CASCADE,
    descendant_id integer NOT NULL REFERENCES tags(id) ON DELETE CASCADE,
    depth         integer NOT NULL,
    PRIMARY KEY (ancestor_id, descendant_id)
);
CREATE INDEX tag_closure_descendant_id_idx ON tag_closure (descendant_id);

INSERT INTO tag_closure (ancestor_id, descendant_id, depth)
WITH RECURSIVE walk (ancestor_id, descendant_id, depth) AS (
    SELECT id, id, 0 FROM tags
    UNION ALL
    SELECT w.ancestor_id, tp.tag_id, w.depth + 1
    FROM walk w JOIN tag_parents tp ON tp.parent_id = w.descendant_id
    WHERE w.depth < 32
)
SELECT ancestor_id, descendant_id, min(depth) FROM walk GROUP BY ancestor_id, descendant_id;

